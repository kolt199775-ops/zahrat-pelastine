const languageButtons = document.querySelectorAll('.language-switch button');
const boxesSlider = document.getElementById('boxesSlider');
const modal = document.getElementById('boxModal');
const modalTitle = modal.querySelector('.modal-title');
const modalDescription = modal.querySelector('.modal-description');
const modalItems = modal.querySelector('.modal-items');
const modalPrice = modal.querySelector('.modal-price');
const modalDelivery = modal.querySelector('.modal-delivery');
const modalImage = modal.querySelector('.modal-image');
const modalClose = modal.querySelector('.modal-close');
const sliderButtons = document.querySelectorAll('.slider-btn');
const yearEl = document.getElementById('year');
const contactPlaceholders = {
  name: document.getElementById('name'),
  email: document.getElementById('email'),
  message: document.getElementById('message')
};

let currentLanguage = 'en';

const getTranslation = (path, lang = currentLanguage) =>
  path.split('.').reduce((acc, key) => (acc && acc[key] !== undefined ? acc[key] : null), translations[lang]);

function updateTexts(lang) {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const text = getTranslation(key, lang);
    if (text) {
      el.textContent = text;
    }
  });

  contactPlaceholders.name.placeholder = translations[lang].contact.placeholders.name;
  contactPlaceholders.email.placeholder = translations[lang].contact.placeholders.email;
  contactPlaceholders.message.placeholder = translations[lang].contact.placeholders.message;

  document.documentElement.lang = lang === 'ar' ? 'ar' : 'en';
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('rtl', lang === 'ar');
}

function renderBoxes(lang = currentLanguage) {
  boxesSlider.innerHTML = '';
  boxesData.forEach((box) => {
    const card = document.createElement('article');
    card.className = 'box-card glass-card';
    card.style.background = `linear-gradient(150deg, ${box.color}, rgba(15, 15, 18, 0.9))`;
    card.innerHTML = `
      <h3>${box.name[lang]}</h3>
      <p>${box.description[lang]}</p>
      <img src="${box.image}" alt="${box.name[lang]}" loading="lazy" />
      <button class="btn primary">${translations[lang].boxes.button}</button>
    `;
    card.querySelector('button').addEventListener('click', () => openModal(box, lang));
    boxesSlider.appendChild(card);
  });
}

function openModal(box, lang = currentLanguage) {
  modalTitle.textContent = box.name[lang];
  modalDescription.textContent = box.description[lang];
  modalItems.innerHTML = '';
  box.items[lang].forEach((item) => {
    const li = document.createElement('li');
    li.textContent = item;
    modalItems.appendChild(li);
  });
  modalPrice.textContent = box.price[lang];
  modalDelivery.textContent = box.delivery[lang];
  modalImage.src = box.image;
  modalImage.alt = box.name[lang];
  modal.classList.add('active');
  modal.setAttribute('aria-hidden', 'false');
}

function closeModal() {
  modal.classList.remove('active');
  modal.setAttribute('aria-hidden', 'true');
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => {
    const lang = button.dataset.lang;
    if (lang === currentLanguage) return;
    currentLanguage = lang;
    languageButtons.forEach((btn) => btn.classList.toggle('active', btn === button));
    updateTexts(lang);
    renderBoxes(lang);
    modal.querySelector('[data-i18n="modal.order"]').textContent = translations[lang].modal.order;
  });
});

sliderButtons.forEach((btn) => {
  btn.addEventListener('click', () => {
    const direction = btn.dataset.direction === 'next' ? 1 : -1;
    boxesSlider.scrollBy({ left: direction * 340, behavior: 'smooth' });
  });
});

modalClose.addEventListener('click', closeModal);
modal.addEventListener('click', (e) => {
  if (e.target === modal) closeModal();
});

document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') closeModal();
});

function init() {
  yearEl.textContent = new Date().getFullYear();
  updateTexts(currentLanguage);
  renderBoxes(currentLanguage);
}

init();
